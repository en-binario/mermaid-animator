// Generates the parts of the site that must match the extension exactly, from the files the extension ships:
//   docs/reference/settings.md          ← packages/extension/package.json contributes.configuration (+ package.nls.json)
//   docs/reference/commands.md          ← contributes.commands, keybindings and menus (+ package.nls.json)
//   docs/changelog.md                   ← packages/extension/CHANGELOG.md
//   static/schemas/animator.schema.json ← packages/extension/schemas/animator.schema.json (its $id points here)
//   static/img/icon.png                 ← packages/extension/media/icon.png
// It runs before `start` and `build` (npm pre-scripts). The outputs are gitignored: edit the sources instead.
import { copyFileSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const SITE = join(dirname(fileURLToPath(import.meta.url)), '..');
const EXTENSION = join(SITE, '..', 'packages', 'extension');
const GITHUB_BLOB = 'https://github.com/en-binario/mermaid-animator/blob/master/packages/extension';
const SCHEMA_URL = 'https://mermaid-animator.enbinario.com/schemas/animator.schema.json';

/** Settings sections, by the key segment after `mermaidAnimator.`. */
const SECTIONS = {
  theme: 'Themes',
  playback: 'Playback',
  scrubber: 'Scrubber',
  display: 'Display',
  camera: 'Camera',
  view: 'Views',
  topology: 'Topology view',
  motion: 'Motion',
  presentation: 'Presentation',
  sync: 'Editor sync',
  liveReload: 'Live reload',
  codeLens: 'CodeLens',
  annotations: 'Annotations',
  files: 'Files',
  diagramsView: 'Mermaid Diagrams view',
  export: 'Export',
};

const pkg = JSON.parse(readFileSync(join(EXTENSION, 'package.json'), 'utf8'));
const nls = JSON.parse(readFileSync(join(EXTENSION, 'package.nls.json'), 'utf8'));
const GENERATED = '<!-- Generated by site/scripts/generate.mjs from the extension. Do not edit; edit the source. -->';

// ---------------------------------------------------------------------------------------------------- helpers

/** Resolves a `%key%` manifest string from package.nls.json (the English strings). */
function t(value) {
  if (typeof value !== 'string') return value;
  const m = /^%(.+)%$/.exec(value);
  if (!m) return value;
  if (!(m[1] in nls)) throw new Error(`package.nls.json has no "${m[1]}"`);
  return nls[m[1]];
}

/** Escapes text for MDX outside inline code spans: `<`, `{` and `}` would otherwise be parsed as JSX. */
function escapeProse(text) {
  return text
    .split(/(`+[^`]*`+)/g)
    .map((part, i) => (i % 2 ? part : part.replace(/</g, '&lt;').replace(/\{/g, '&#123;').replace(/\}/g, '&#125;')))
    .join('');
}

const SETTING_IDS = new Set([pkg.contributes.configuration].flat().flatMap((s) => Object.keys(s.properties)));

/** `#setting.id#` links become links to the setting's anchor, or plain code for VS Code's own settings. */
function settingLinks(text) {
  return text.replace(/`?#([\w.-]+)#`?/g, (_, id) => (SETTING_IDS.has(id) ? `[\`${id}\`](#${anchor(id)})` : `\`${id}\``));
}

function anchor(id) {
  return id.toLowerCase().replace(/[^a-z0-9]+/g, '-').replace(/^-|-$/g, '');
}

/** A table cell: pipes are escaped even inside code spans (GitHub-flavoured Markdown tables). */
function cell(text) {
  return text.replace(/\|/g, '\\|').replace(/\n+/g, ' ');
}

function inlineValue(value) {
  return '`' + JSON.stringify(value).replace(/,/g, ', ').replace(/:/g, ': ') + '`';
}

function describe(schema) {
  return settingLinks(escapeProse(t(schema.markdownDescription ?? schema.description ?? '')));
}

function shapeOf(schema) {
  return schema.additionalProperties?.properties ?? schema.items?.properties ?? schema.properties ?? null;
}

function write(rel, content) {
  const path = join(SITE, rel);
  mkdirSync(dirname(path), { recursive: true });
  writeFileSync(path, content.replace(/\n{3,}/g, '\n\n'));
  console.log(`generated ${rel}`);
}

// ---------------------------------------------------------------------------------------------------- settings

function settingsPage() {
  const properties = Object.assign({}, ...[pkg.contributes.configuration].flat().map((s) => s.properties));
  const groups = new Map();
  for (const [id, schema] of Object.entries(properties)) {
    const parts = id.split('.');
    const group = parts.length > 2 ? parts[1] : 'general';
    if (!groups.has(group)) groups.set(group, []);
    groups.get(group).push([id, schema]);
  }

  const out = [
    '---',
    'title: Settings reference',
    'description: Every Mermaid Animator setting with its type, default value and allowed values.',
    'sidebar_label: Settings',
    // The table of contents lists the sections; setting ids are too long for the narrow column.
    'toc_max_heading_level: 2',
    '---',
    '',
    GENERATED,
    '',
    '# Settings reference',
    '',
    `Mermaid Animator has ${Object.keys(properties).length} settings. Open them with the gear button at the end of the`,
    'panel toolbar or **Mermaid Animator: Open Settings**, or search for `mermaidAnimator` in the Settings editor.',
    'One diagram can override most of them with [`@animator`](../authoring/annotations.md#animator) or a',
    '[sidecar file](../authoring/sidecar-files.md).',
    '',
    'This page is generated from the extension manifest on every build, so it always matches the released version.',
    '',
  ];

  const order = [...Object.keys(SECTIONS), ...groups.keys()].filter((g, i, all) => groups.has(g) && all.indexOf(g) === i);
  for (const group of order) {
    out.push(`## ${SECTIONS[group] ?? group}`, '');
    for (const [id, s] of groups.get(group)) {
      out.push(`### \`${id}\` {#${anchor(id)}}`, '');
      const facts = [];
      const type = [s.type].flat().filter(Boolean).join(' | ');
      if (type) facts.push(`**Type:** \`${type}\``);
      const long = 'default' in s && JSON.stringify(s.default).length > 60;
      if ('default' in s) facts.push(long ? '**Default:** see below' : `**Default:** ${inlineValue(s.default)}`);
      if (typeof s.minimum === 'number' || typeof s.maximum === 'number') {
        facts.push(`**Range:** ${s.minimum ?? '…'} to ${s.maximum ?? '…'}`);
      }
      if (s.scope) facts.push(`**Scope:** \`${s.scope}\``);
      if (facts.length) out.push(facts.join(' · '), '');
      const deprecation = t(s.markdownDeprecationMessage ?? s.deprecationMessage);
      if (deprecation) out.push(':::warning[Deprecated]', '', settingLinks(escapeProse(deprecation)), '', ':::', '');
      const description = describe(s);
      if (description) out.push(description, '');
      const values = s.enum ?? s.items?.enum;
      if (values) {
        const notes = (s.markdownEnumDescriptions ?? s.enumDescriptions ?? s.items?.enumDescriptions ?? []).map(t);
        out.push('| Value | Meaning |', '|---|---|');
        values.forEach((v, i) => out.push(`| ${cell(inlineValue(v))} | ${cell(settingLinks(escapeProse(notes[i] ?? '')))} |`));
        out.push('');
      }
      const shape = shapeOf(s);
      if (shape) {
        out.push(s.type === 'array' ? 'Each entry has these keys:' : 'Keys:', '', '| Key | Type | Description |', '|---|---|---|');
        for (const [k, sub] of Object.entries(shape)) {
          const subType = [sub.type].flat().filter(Boolean).join(' | ');
          out.push(`| \`${k}\` | ${cell(subType ? '`' + subType + '`' : '')} | ${cell(describe(sub))} |`);
        }
        out.push('');
      }
      if (long) out.push('Default:', '', '```json', JSON.stringify(s.default, null, 2), '```', '');
    }
  }
  return out.join('\n');
}

// ---------------------------------------------------------------------------------------------------- commands

function key(binding, mac) {
  const k = mac ? (binding.mac ?? binding.key) : binding.key;
  return k
    .split(' ')
    .map((chord) => chord.split('+').map((p) => p.charAt(0).toUpperCase() + p.slice(1)).join('+'))
    .map((chord) => `\`${chord}\``)
    .join(' ');
}

function commandsPage() {
  const { commands, keybindings = [], menus = {} } = pkg.contributes;
  const hidden = new Set((menus.commandPalette ?? []).filter((m) => m.when === 'false').map((m) => m.command));
  const titleOf = (c) => `${c.category ? t(c.category) + ': ' : ''}${t(c.title)}`;
  const out = [
    '---',
    'title: Commands and keyboard shortcuts',
    'description: Every Mermaid Animator command with its identifier and default keyboard shortcut.',
    'sidebar_label: Commands',
    '---',
    '',
    GENERATED,
    '',
    '# Commands and keyboard shortcuts',
    '',
    'Run commands from the Command Palette (`Ctrl+Shift+P`, `Cmd+Shift+P` on macOS) by typing `Mermaid Animator`.',
    'Bind any of them to a key in **Preferences: Open Keyboard Shortcuts** using its identifier. The animator panel',
    'has its own single-key shortcuts, listed in [Keyboard shortcuts](../guide/keyboard.md).',
    '',
    '## Default keyboard shortcuts',
    '',
    '| Command | Windows and Linux | macOS | When |',
    '|---|---|---|---|',
  ];
  for (const b of keybindings) {
    const c = commands.find((x) => x.command === b.command);
    out.push(`| **${escapeProse(c ? titleOf(c) : b.command)}** | ${key(b, false)} | ${key(b, true)} | ${cell(b.when ? '`' + b.when + '`' : 'Always')} |`);
  }
  out.push('', '## All commands', '', '| Command | Identifier |', '|---|---|');
  for (const c of commands) {
    const note = hidden.has(c.command) ? ' <br/><small>Menus and views only, not in the Command Palette</small>' : '';
    out.push(`| **${escapeProse(titleOf(c))}**${note} | \`${c.command}\` |`);
  }
  return out.join('\n') + '\n';
}

// ---------------------------------------------------------------------------------------------------- changelog

function changelogPage() {
  const source = readFileSync(join(EXTENSION, 'CHANGELOG.md'), 'utf8').replace(/\r\n/g, '\n');
  let inFence = false;
  const body = source
    .split('\n')
    .filter((line, i) => !(i === 0 && line.startsWith('# ')))
    .map((line) => {
      if (line.startsWith('```')) inFence = !inFence;
      if (inFence || line.startsWith('```')) return line;
      const linked = line.replace(/\]\((?!https?:|#|mailto:)([^)]+)\)/g, (_, p) => `](${GITHUB_BLOB}/${p.replace(/^\.\//, '')})`);
      return escapeProse(linked);
    })
    .join('\n');
  return ['---', 'title: Changelog', 'description: What changed in each Mermaid Animator release.', '---', '', GENERATED, '', '# Changelog', body].join('\n');
}

// ---------------------------------------------------------------------------------------------------- assets

function copyAssets() {
  const schema = JSON.parse(readFileSync(join(EXTENSION, 'schemas', 'animator.schema.json'), 'utf8'));
  if (schema.$id !== SCHEMA_URL) {
    throw new Error(`animator.schema.json has $id ${schema.$id}; the site serves it at ${SCHEMA_URL}`);
  }
  mkdirSync(join(SITE, 'static', 'schemas'), { recursive: true });
  copyFileSync(join(EXTENSION, 'schemas', 'animator.schema.json'), join(SITE, 'static', 'schemas', 'animator.schema.json'));
  mkdirSync(join(SITE, 'static', 'img'), { recursive: true });
  copyFileSync(join(EXTENSION, 'media', 'icon.png'), join(SITE, 'static', 'img', 'icon.png'));
  console.log('copied the sidecar schema and the icon');
}

write('docs/reference/settings.md', settingsPage());
write('docs/reference/commands.md', commandsPage());
write('docs/changelog.md', changelogPage());
copyAssets();
