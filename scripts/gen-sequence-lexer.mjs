// Generates packages/core/src/sequence/lexerRules.generated.ts from the pinned Mermaid
// package, so the native lexer uses exactly Mermaid's token regular expressions.
// Run after upgrading Mermaid: `node scripts/gen-sequence-lexer.mjs`.
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const require = createRequire(import.meta.url);
const pkgDir = path.dirname(require.resolve('mermaid/package.json'));
const version = JSON.parse(readFileSync(path.join(pkgDir, 'package.json'), 'utf8')).version;
const chunkDir = path.join(pkgDir, 'dist/chunks/mermaid.core');
const file = readdirSync(chunkDir).find((f) => /^sequenceDiagram-.*\.mjs$/.test(f));
if (!file) throw new Error('sequence diagram chunk not found');
const src = readFileSync(path.join(chunkDir, file), 'utf8');

const start = src.indexOf('rules: [/^(?:');
const end = src.indexOf('],', start);
const rules = (0, eval)(src.slice(start + 7, end + 1));
const condStart = src.indexOf('conditions:', start);
const condEnd = src.indexOf('\n', condStart);
const conditions = JSON.parse(src.slice(condStart + 'conditions:'.length, condEnd).trim().replace(/,$/, ''));

const lines = [
  `// GENERATED by scripts/gen-sequence-lexer.mjs from mermaid@${version} (MIT, (c) Knut Sveidqvist and contributors).`,
  '// Do not edit by hand: regenerate after upgrading Mermaid.',
  '',
  `export const MERMAID_VERSION = '${version}';`,
  '',
  '/** Token regular expressions in Mermaid rule order, without the leading `^` (compiled sticky + case-insensitive). */',
  'export const RULE_SOURCES: readonly string[] = [',
  ...rules.map((r, i) => `  /* ${String(i).padStart(2)} */ ${JSON.stringify(r.source.replace(/^\^/, ''))},`),
  '];',
  '',
  '/** Rule indices active in each lexer state. */',
  'export const STATE_RULES: Readonly<Record<string, readonly number[]>> = {',
  ...Object.entries(conditions).map(([state, c]) => `  ${JSON.stringify(state)}: [${c.rules.join(', ')}],`),
  '};',
  '',
];
const here = path.dirname(fileURLToPath(import.meta.url));
const out = path.resolve(here, '../packages/core/src/sequence/lexerRules.generated.ts');
writeFileSync(out, lines.join('\n'));
console.log(`wrote ${out} (${rules.length} rules, mermaid@${version})`);
