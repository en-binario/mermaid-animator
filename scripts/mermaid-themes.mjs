// Generates the Mermaid theme palettes (spec visual-theme: Mermaid theme palettes) from the pinned
// Mermaid: packages/renderer/src/mermaidPalettes.generated.ts and the marked region of tokens.css.
// Usage: node scripts/mermaid-themes.mjs [--check]   (--check exits 1 when the files are out of date)
import * as esbuild from 'esbuild';
import { readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { mermaidParse } from './mermaid-jsdom.mjs';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const src = path.join(root, 'packages/renderer/src');
const tsFile = path.join(src, 'mermaidPalettes.generated.ts');
const cssFile = path.join(src, 'tokens.css');
const THEMES = ['default', 'neutral', 'dark', 'forest', 'base', 'neo', 'neo-dark', 'redux', 'redux-dark', 'redux-color', 'redux-dark-color'];
const TOKENS = ['canvas', 'surface', 'surface-sunken', 'hairline', 'rule', 'ink-1', 'ink-2', 'ink-3', 'accent', 'accent-muted', 'brass', 'sage', 'note-fill', 'note-rule', 'crimson', 'viridian'];
const BEGIN = '/* <mermaid-palettes> generated by scripts/mermaid-themes.mjs; do not edit */';
const END = '/* </mermaid-palettes> */';

// The mapping lives in TypeScript (shared with the renderer and its tests): bundle it for Node.
const bundle = await esbuild.build({
  stdin: {
    contents: "export { mermaidPalette, MERMAID_THEME_KEYS, isDarkCanvas } from './mermaidPalette'; export { INK_IVORY_PALETTES } from './palettes';",
    resolveDir: src,
    loader: 'ts',
  },
  bundle: true,
  write: false,
  format: 'esm',
  platform: 'node',
});
const lib = await import(`data:text/javascript;base64,${Buffer.from(bundle.outputFiles[0].text).toString('base64')}`);

await mermaidParse('graph TD; A-->B'); // installs the jsdom globals and initialises Mermaid
const { default: mermaid } = await import('mermaid');
const version = JSON.parse(readFileSync(path.join(root, 'node_modules/mermaid/package.json'), 'utf8')).version;

const palettes = {};
for (const theme of THEMES) {
  mermaid.initialize({ startOnLoad: false, theme });
  const all = mermaid.mermaidAPI.getConfig().themeVariables;
  const vars = Object.fromEntries(lib.MERMAID_THEME_KEYS.map((k) => [k, String(all[k])]));
  palettes[`mermaid-${theme}`] = lib.mermaidPalette(vars, lib.INK_IVORY_PALETTES.ivory, lib.INK_IVORY_PALETTES.graphite);
}

const ts = `// Generated by scripts/mermaid-themes.mjs from mermaid ${version}; do not edit.
// Regenerate after a Mermaid upgrade: node scripts/mermaid-themes.mjs
import type { ColorToken } from './theme';

export const MERMAID_PALETTE_SOURCE = 'mermaid ${version}';

export const MERMAID_PALETTES = {
${Object.entries(palettes)
  .map(([name, p]) => `  '${name}': {\n${TOKENS.map((t) => `    '${t}': '${p[t]}',`).join('\n')}\n  },`)
  .join('\n')}
} as const satisfies Record<string, Record<ColorToken, string>>;
`;

const rgb = (hex) => [1, 3, 5].map((i) => parseInt(hex.slice(i, i + 2), 16)).join(' ');
const css = [
  BEGIN,
  ...Object.entries(palettes).map(([name, p]) => {
    const dark = lib.isDarkCanvas(p.canvas);
    return [
      `[data-palette='${name}'] {`,
      ...TOKENS.map((t) => `  --ma-${t}: ${p[t]};`),
      `  --ma-pulse-halo: rgb(${rgb(p.accent)} / 22%);`,
      ...(dark ? ['  --ma-elevation-1: none;'] : []),
      `  color-scheme: ${dark ? 'dark' : 'light'};`,
      '}',
    ].join('\n');
  }),
  END,
].join('\n\n');

const tokens = readFileSync(cssFile, 'utf8');
const start = tokens.indexOf(BEGIN);
const end = tokens.indexOf(END);
const nextTokens = start >= 0 && end > start ? tokens.slice(0, start) + css + tokens.slice(end + END.length) : `${tokens.trimEnd()}\n\n${css}\n`;
const currentTs = (() => {
  try {
    return readFileSync(tsFile, 'utf8');
  } catch {
    return '';
  }
})();

if (process.argv.includes('--check')) {
  const stale = [currentTs !== ts && tsFile, nextTokens !== tokens && cssFile].filter(Boolean);
  if (stale.length) {
    console.error(`Out of date (run node scripts/mermaid-themes.mjs): ${stale.map((f) => path.relative(root, f)).join(', ')}`);
    process.exit(1);
  }
  console.log(`Mermaid palettes match mermaid ${version}.`);
} else {
  writeFileSync(tsFile, ts);
  writeFileSync(cssFile, nextTokens);
  console.log(`Wrote ${Object.keys(palettes).length} palettes from mermaid ${version}.`);
}
